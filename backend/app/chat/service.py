def archive_conversation(conversation_id: str, user_id: int) -> bool:
    """
    Archive a conversation
    """
    try:
        with get_db_context() as db:
            result = db.execute(
                "UPDATE conversations SET state = 'archived', updated_at = ? WHERE id = ? AND user_id = ?",
                (datetime.datetime.now(), conversation_id, user_id)
            )
            db.commit()
            
            if result.rowcount > 0:
                logger.info(f"✅ Archived conversation: {conversation_id}")
                return True
            else:
                logger.warning(f"⚠️ Conversation {conversation_id} not found or doesn't belong to user {user_id}")
                return False
            
    except Exception as e:
        logger.error(f"❌ Failed to archive conversation {conversation_id}: {str(e)}")
        return False

