def delete_conversation(conversation_id: str, user_id: int) -> bool:
    """
    Delete conversation and associated data
    """
    try:
        with get_db_context() as db:
            # Verify conversation belongs to user
            conversation = db.execute(
                "SELECT id FROM conversations WHERE id = ? AND user_id = ?",
                (conversation_id, user_id)
            ).fetchone()
            
            if not conversation:
                logger.warning(f"⚠️ Conversation {conversation_id} not found or doesn't belong to user {user_id}")
                return False
            
            # Delete associated image files from disk
            images = db.execute(
                "SELECT file_path FROM media_library WHERE conversation_id = ? AND media_type = 'image'",
                (conversation_id,)
            ).fetchall()
            for row in images:
                fpath = row[0]
                if fpath and os.path.exists(fpath):
                    try:
                        os.remove(fpath)
                    except OSError:
                        pass

            # Delete messages
            db.execute("DELETE FROM messages WHERE conversation_id = ?", (conversation_id,))

            # Delete file references
            db.execute("DELETE FROM file_references WHERE conversation_id = ?", (conversation_id,))

            # Delete conversation
            db.execute("DELETE FROM conversations WHERE id = ?", (conversation_id,))
            
            db.commit()
            
            logger.info(f"✅ Deleted conversation: {conversation_id}")
            return True
        
    except Exception as e:
        logger.error(f"❌ Failed to delete conversation {conversation_id}: {str(e)}")
        return False

